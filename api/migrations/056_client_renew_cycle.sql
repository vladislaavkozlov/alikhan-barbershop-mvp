-- Окно 59 «Недополученная прибыль» (22.08.2026). Срок, через который клиент должен
-- вернуться за обновлением стрижки, и почему он именно такой.
--
-- Ключевое решение Влада, зафиксированное здесь навсегда, чтобы к нему не вернулись
-- «улучшением по алгоритму»: срок НЕ выводится из истории клиента и НЕ берётся нормой
-- по услуге. Это договорённость мастера с клиентом, произнесённая вслух в конце
-- визита и записанная мастером. Причины:
--   1) вывод срока из личной истории требует 2+ визитов, а два визита - не статистика;
--   2) главное - такой вывод закодировал бы недоработку салона как «особенность
--      клиента». Человек ходит раз в два месяца не потому, что ему так надо, а потому
--      что ему никто не сказал, что стрижка держит форму три недели. Алгоритм объявил
--      бы это нормой, и салон продолжил бы терять половину денег с этого человека;
--   3) норма «по услуге» общая, а стрижки и волосы разные.
--
-- renew_days - срок, по которому реально живут все расчёты (просрочен / разрежён /
-- в сроке) и будущие напоминания. renew_days_recommended - срок, который мастер
-- назвал правильным для этой стрижки. Они специально разные колонки: разрыв между
-- «как надо» и «на что согласился клиент» - это и есть недополученные деньги, и в
-- v1 он только копится (адресные пакеты стрижек - следующие окна), нигде не
-- показывается отдельной метрикой.
--
-- renew_reason - ключ из закрытого списка (api/lib/renew-reason.js, зеркало подписей
-- на фронте - assets/renew-reason.js). Как и у client_source (миграция 050), словарь
-- не закрепляется CHECK-констрейнтом: пополнение списка не должно требовать миграции
-- с блокировкой таблицы на проде, допустимость значения держит нормализация на входе.
--
-- Все колонки NULL. Это не «неполные данные»: база перед передачей Алихану будет
-- очищена, и каждый клиент с первого визита заведётся уже со сроком - поле
-- обязательно при закрытии визита. У существующих тестовых строк поле просто пустое,
-- бэкфилл-эвристик здесь намеренно нет: выдуманный срок хуже пустого.
ALTER TABLE clients ADD COLUMN IF NOT EXISTS renew_days integer;
ALTER TABLE clients ADD COLUMN IF NOT EXISTS renew_days_recommended integer;
ALTER TABLE clients ADD COLUMN IF NOT EXISTS renew_reason text;
ALTER TABLE clients ADD COLUMN IF NOT EXISTS renew_note text;
-- Кто и когда поставил срок последним. Отдельной таблицы истории в v1 нет осознанно:
-- «кто и когда поставил последним» отвечает на вопрос владельца «с кого спросить»,
-- а полная история изменений без своего экрана была бы мёртвыми данными.
ALTER TABLE clients ADD COLUMN IF NOT EXISTS renew_set_by text;
ALTER TABLE clients ADD COLUMN IF NOT EXISTS renew_set_at timestamptz;
