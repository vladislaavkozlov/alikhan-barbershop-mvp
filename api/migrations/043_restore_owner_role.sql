-- 11.08.2026, инцидент прав: владелец сменил СЕБЕ роль на 'мастер' в кабинете
-- (PUT /staff/master-1/role) и запер систему - право менять роли есть только у
-- owner (api/routes/staff.js, handleStaffRole → requireRole(auth, ['owner'])), а
-- других владельцев на проде не осталось: все тестовые и QA-owner-аккаунты
-- вычищены миграциями 014/024/027/035/039 (сверено grep по всем DELETE FROM staff).
-- Итог - роль назад вернуть было НЕКОМУ ни одним запросом из интерфейса, и сам
-- Алиовсад попадал в кабинет мастера (assets/crm-auth.js, редирект по ROLE_PAGE).
--
-- Живые сотрудники на этот момент: master-1 Алиовсад (owner, фактический владелец
-- бизнеса), master-2 Мамедхан (admin, миграция 014), master-3 Елизавета (master).
--
-- Восстанавливаем ровно то состояние, что задала миграция 011_real_master_names.sql
-- ("Алиовсад стрижёт сам, поэтому provides_services=true, но роль owner") - никаких
-- других полей не трогаем: location_id, provides_services, has_system_access,
-- pin_hash остались как были, роль менялась одним UPDATE и возвращается одним.
--
-- Идемпотентна: если роль уже owner - ноль строк, ноль эффекта.
UPDATE staff SET role = 'owner' WHERE id = 'master-1' AND role <> 'owner';

-- Страховка от повторения на уровне ДАННЫХ, а не только кода: если по любой
-- причине (ручной SQL, будущая правка роута) в staff не осталось ни одного
-- владельца - возвращаем роль основателю. Без этого система снова оказалась бы
-- запертой, и починить её можно было бы только новой миграцией, то есть деплоем.
-- Технический замок в самом роуте (сервер не отдаёт последнюю owner-роль) - в
-- этой же правке, api/routes/staff.js.
UPDATE staff SET role = 'owner'
 WHERE id = 'master-1'
   AND NOT EXISTS (SELECT 1 FROM staff WHERE role = 'owner');
