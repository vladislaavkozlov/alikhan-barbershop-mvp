-- Топ-мастер по услуге (20.08.2026, постановка Влада: «в CRM у владельца опция выбрать
-- топ-мастера услуги - галка "топ услуга" в карточке сотрудника - и на сайте он стал бы
-- для этой услуги топ-мастером; клиент выбирает услугу, а дальше "у обычного мастера за
-- стандартную оплату" или "у топ мастера за +"»).
--
-- Флаг на паре (мастер, услуга), а не на мастере целиком: барбершоп продаёт по-разному
-- разные услуги одного человека - он может быть топом по стрижке и обычным по бороде.
-- Живёт в той же строке, что и его цена (master_services.price существует с Окна 8,
-- 002_schema.sql), поэтому «топ» и «сколько стоит топ» физически не могут разъехаться.
--
-- Отдельной колонки «надбавка за топ» сознательно НЕТ: надбавка - это разница цен, а
-- второе поле про те же деньги в первый же день разойдётся с прайсом (тот же довод, по
-- которому client_source в миграции 050 - ключ словаря, а не свободный текст).
ALTER TABLE master_services ADD COLUMN IF NOT EXISTS is_top boolean NOT NULL DEFAULT false;

-- Условия, на которых сделана запись: 'standard' | 'top'. NULL - брони, созданные до
-- этой миграции: у них тарифа не было, и показывать им «стандартный» задним числом
-- нельзя - это было бы выдуманным фактом в отчётности владельца.
--
-- Хранится на брони, а не вычисляется на лету по текущей галке: владелец снимет топ с
-- мастера в сентябре, а августовская запись обязана помнить, на каких условиях клиент
-- записался и почему в чеке была та цена (тот же принцип, что у client_source, 050).
--
-- CHECK-констрейнта нет намеренно: тарифов может стать три ('vip'), и пополнение словаря
-- не должно требовать миграции с блокировкой таблицы на живом проде. Допустимые значения
-- держит сервер (MASTER_TIERS в api/routes/bookings.js).
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS master_tier text;
