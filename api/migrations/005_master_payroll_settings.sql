-- Окно 10 (30.07.2026): формула зарплаты - по мастеру, не единый % на категорию
-- услуги (разд.17.3 ТЗ). Старая payroll_settings (одна строка на всех, % по
-- категории base/complex + бонус за нового клиента) реальности не соответствует:
-- Али и Мамедхан получают 100% от выручки по своим услугам, Елизавета - 40% или
-- 50% в зависимости от клиентской базы (точный порог перехода Алихан не назвал -
-- не выдумываем, ставка остаётся редактируемым полем владельца, не авто-расчётом).
-- payroll_settings и её колонки (pct_base_service/new_client_bonus/...) не
-- удаляем - просто больше не используются в активном расчёте (разд.17.4/17.5).
CREATE TABLE master_payroll_settings (
  master_id text primary key references staff(id),
  pct numeric not null check (pct >= 0 and pct <= 100)
);

