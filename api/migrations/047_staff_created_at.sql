-- Порядок сотрудников: старые сверху, новые снизу (Влад, 13.08.2026).
--
-- До этой миграции GET /staff читал таблицу вообще без ORDER BY - Postgres отдаёт
-- строки в порядке физического хранения, а он меняется при каждом UPDATE строки
-- (обновлённая строка переезжает в конец кучи). Отсюда и картинка на бою: сверху
-- оказывался Мамедхан, хотя первым в салоне появился Алиовсад - просто его карточку
-- правили позже. Никакого поля "когда завели" в таблице не было вообще, поэтому
-- любой стабильный порядок пришлось бы выдумывать из имени или id.
--
-- created_at появляется у всех строк со значением по умолчанию now(), то есть у трёх
-- уже существующих сотрудников время будет ОДИНАКОВЫМ - разложить их по этому полю
-- нельзя. Разбирает ничью сортировка вторым ключом по id: у исторических сотрудников
-- id проставлялись руками по порядку появления (master-1 Алиовсад, master-2 Мамедхан,
-- master-3 Елизавета), а все, кого заводят через интерфейс, получают id вида
-- staff-<hex> - он всегда больше "master-..." при сравнении строк, поэтому новые
-- аккаунты уходят вниз и без разницы во времени. Дальше порядок держит уже сам
-- created_at: каждый следующий созданный аккаунт получает более позднее время.
--
-- Колонка nullable-безопасна для старых записей за счёт DEFAULT, ничего не удаляет
-- и не переписывает - миграция не трогает ни одной существующей ячейки.
ALTER TABLE staff ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();

-- Индекс под тот самый порядок, которым теперь отдаётся список команды.
CREATE INDEX IF NOT EXISTS staff_created_at_idx ON staff (created_at, id);
