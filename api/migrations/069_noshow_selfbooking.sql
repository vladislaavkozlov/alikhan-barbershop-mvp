-- 1. «Нахера администратору с ним связываться, он сам может через форму новое время
--    себе выбрать». Верно: перенос чужой брони ботом - риск для расписания, а вот
--    новая запись на свободный слот - обычная самозапись, ровно то же, что делает
--    любой клиент с сайта. Чтобы бот мог дать человеку ссылку, заведению нужен адрес
--    его формы записи: домена мало (сайты клиентов живут на общем github.io, у каждого
--    свой путь и свой ключ в адресе, см. миграцию 067).
--    Адрес не задан - бот ведёт себя как раньше и зовёт администратора: обещать
--    самозапись там, где ссылки нет, значит обещать неработающее.
ALTER TABLE tenants ADD COLUMN IF NOT EXISTS booking_url text;

