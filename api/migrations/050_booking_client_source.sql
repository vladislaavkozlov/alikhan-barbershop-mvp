-- Источник клиента на брони (17.08.2026, Влад: "в карточке записи 'День' показывать
-- откуда пришёл клиент - через яндекс карты или 2гис"). До этой миграции такого поля
-- в системе не было вообще: `staff_comment` (миграция 048) - про другое (почему
-- фактическая сумма отличается от прайса) и заполняется только при редактировании,
-- а свободным текстом каналы всё равно не посчитаешь ("2гис" / "2 гис" / "карты" -
-- три разные строки об одном).
--
-- Хранится на брони, а не на клиенте (clients), по двум причинам:
--   1) walk-in без телефона живёт вообще без client_id (решение Алихана, миграция
--      041) - источник таких визитов на клиенте физически негде держать;
--   2) один и тот же человек может прийти по карте, а через полгода по рекомендации -
--      колонка на клиенте затёрла бы первое привлечение вторым.
--
-- Значения - ключи из фиксированного словаря (assets/client-source.js, зеркало на
-- сервере - CLIENT_SOURCE_KEYS в api/routes/bookings.js), не свободный текст: только
-- так владелец сможет посчитать, сколько клиентов дал каждый канал. Проверку
-- допустимых значений держит нормализация на входе (normalizeClientSource), а не
-- CHECK-constraint: словарь каналов будет пополняться (появится новая площадка), и
-- пополнение не должно требовать миграции с блокировкой таблицы на проде.
--
-- NULL - штатное состояние, а не пропуск: клиент, пришедший пешком или по звонку,
-- источника в технике не имеет, и врать о нём система не должна.
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS client_source text;

-- Индекс под метку "+1 новый клиент" в карточке дня: на каждый рендер дня сервер
-- спрашивает историю клиентов этой выборки ("была ли у него бронь раньше"), а
-- единственный индекс bookings до сих пор был по (master_id, date) - поиск по
-- client_id шёл полным перебором таблицы на каждое открытие расписания.
CREATE INDEX IF NOT EXISTS bookings_client_history_idx ON bookings (client_id, date, start_time);
