-- 20.08.2026, правка Влада: уведомление можно убрать из колокольчика, а в разделе
-- «Уведомления» оно остаётся. Колокольчик - место «что нового прямо сейчас», раздел -
-- полный журнал записей; до этой колонки они показывали ровно один и тот же список, и
-- разобранное уведомление висело в шапке до тех пор, пока его не вытеснят шесть новых.
--
-- Отдельная колонка, а не read_at: прочитано и убрано - разные вещи. Владелец может
-- прочитать уведомление и оставить его в колокольчике как напоминание, а может убрать
-- не читая. Раздел не смотрит на dismissed_at вовсе - там журнал за всё время.
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS dismissed_at timestamptz;

-- Колокольчик спрашивает «непрочитанные и неубранные» на каждом тике счётчика (раз в
-- 45 секунд у каждого открытого кабинета) - частичный индекс держит этот запрос на
-- живых строках, не заставляя базу перебирать весь журнал.
CREATE INDEX IF NOT EXISTS notifications_bell_idx
  ON notifications (staff_id, created_at DESC)
  WHERE dismissed_at IS NULL;
