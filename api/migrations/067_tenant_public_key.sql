-- Ключ заведения для публичных запросов с общего домена (01.09.2026).
--
-- Зачем. Сервер узнаёт заведение по домену страницы (миграция 059), и это верно
-- для кабинета: у каждого клиента свой адрес. Но сайты живут иначе. GitHub Pages
-- отдаёт ОДИН домен на все репозитории аккаунта, поэтому тестовый сайт клиники
-- Урбашевичус и боевой сайт барбершопа Алихана приходят с одного и того же
-- vladislaavkozlov.github.io. По домену их не различить.
--
-- Ключ решает ровно это и ничего больше: он действует только на публичных
-- роутах - каталог услуг, свободное время, создание записи. Всё, что за логином,
-- по-прежнему определяется доменом, иначе ключом можно было бы притвориться
-- чужим кабинетом.
--
-- Отдельный список источников, а не domains: домен кабинета и сайт, которому
-- разрешено обращаться с ключом, - разные вещи. Один общий список означал бы,
-- что github.io становится «доменом Карины» и её кабинет открывается по чужому
-- адресу.
ALTER TABLE tenants ADD COLUMN IF NOT EXISTS public_key text;
ALTER TABLE tenants ADD COLUMN IF NOT EXISTS widget_origins text[] NOT NULL DEFAULT '{}';

CREATE UNIQUE INDEX IF NOT EXISTS tenants_public_key_uniq
  ON tenants (public_key) WHERE public_key IS NOT NULL;
