-- Окно «Увольнение сотрудника» (22.08.2026). Увольнение в CRM - это НЕ удаление
-- строки из staff: на сотрудника ссылаются bookings.master_id, master_services,
-- master_payroll_settings и вся аналитика. Физическое удаление либо валит FK, либо
-- оставляет выручку без владельца (инцидент 04.08.2026 - DELETE FROM staff в
-- миграции уронил прод на ~20 минут). Флаг employed для этого был всегда, здесь к
-- нему добавляется дата: без неё нельзя сказать «работал до 15 июня» ни в карточке
-- команды, ни в блоке зарплат за прошлый период.
-- NULL = человек в команде (либо уволен ещё до появления этой колонки - тогда дата
-- неизвестна честно, а не выдумана задним числом).
ALTER TABLE staff ADD COLUMN IF NOT EXISTS employment_ended_at date;
