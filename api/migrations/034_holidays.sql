-- Окно 24 (05.08.2026) - производственный календарь как ДАННЫЕ, а не текст в разметке.
-- До этой миграции праздники существовали только как 12 захардкоженных строк во
-- вкладке "Год" (crm-owner.html, комментарий там же признавал: справочный статичный
-- блок). Движок записи про них не знал вообще: если салон реально закрыт 1 января,
-- клиент всё равно мог записаться - никакой связи между "красным днём календаря" и
-- schedule_shifts не существовало.
--
-- Таблица намеренно минимальная (дата + название). Признак "выходной ли это для
-- конкретного мастера" здесь НЕ хранится: он и так живёт в schedule_shifts/
-- schedule_breaks (см. getEffectiveSchedule/isScheduleDayOff в server.mjs), и
-- дублировать его вторым источником истины значило бы гарантированно их рассинхронить.
-- Праздник и рабочий статус дня - два независимых признака одной даты: мастер может
-- сам выйти работать 23 февраля, день останется рабочим, а день останется праздничным.
CREATE TABLE IF NOT EXISTS holidays (
  date DATE PRIMARY KEY,
  name TEXT NOT NULL
);

