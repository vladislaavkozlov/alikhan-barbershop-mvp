-- помнит. Комментарий живёт на самой брони, поэтому виден и через месяц - и в
-- карточке записи (клик по ней в календаре любого прошедшего дня), и в истории
-- визитов карточки клиента).
--
-- staff_comment, не comment: COMMENT - команда SQL, а имена master_comment/
-- owner_comment уже заняты в schedule_change_requests (миграция 016) под тем же
-- смыслом "текст, который написал сотрудник" - держим то же соглашение.
-- Пишется вместе с actual_price одним роутом PATCH /bookings/:id/actual-price
-- (обе цифры сотрудник вводит в одном месте карточки, разводить их по двум
-- запросам смысла нет), видимость - owner/admin, как у самой actual_price.
