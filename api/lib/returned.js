// Счётчик возвращённых денег: какие визиты система имеет право записать себе в заслугу
// и на какую сумму (02.09.2026).
//
// Зачем это отдельно от «Недополученной прибыли». Та карточка отвечает на вопрос
// «сколько утекло», эта - «сколько вернули». Первая нужна, чтобы владелец клиники
// увидел проблему, вторая - чтобы он увидел, за что платит. На второй держится
// гарантия «не вернули больше стоимости подписки - месяц не оплачивается», поэтому
// цифра здесь должна выдерживать спор с самим владельцем.
//
// Главное правило, которое здесь важнее любой полноты подсчёта: ВИЗИТ БЕЗ
// ДОСТАВЛЕННОГО СООБЩЕНИЯ НЕ ЗАСЧИТЫВАЕТСЯ. Система не приписывает себе человека,
// которому ничего не отправляла, даже если он идеально подходит по всем прочим
// признакам. Соблазн считать иначе велик - цифра сразу вырастет в разы - но такую
// цифру нельзя показать владельцу клиники, который спросит «а он бы и сам не пришёл?».
//
// Почему обычный визит в срок не считается возвратом. Человек, который ходит по
// своему сроку, без неявок в прошлом, пришёл бы и без нас. Записать его в возврат
// значило бы объявить своей заслугой всю выручку клиники - ровно та подмена, из-за
// которой аналитике в подобных системах не верят.

// Основания в порядке убывания надёжности. Порядок в массиве - это и есть приоритет:
// визит засчитывается один раз, по первому подошедшему основанию, иначе один человек
// попал бы в сумму трижды.
export const RETURN_REASONS = Object.freeze(['confirmed', 'reminded_risky', 'returned_overdue']);

// Какое основание даёт состоявшийся визит, или null, если оснований нет.
//
// messageSent     - по этой брони системой доставлено хотя бы одно сообщение
//                   (status='sent'): подтверждение записи, напоминание за сутки или
//                   за два часа. Без него весь расчёт бессмыслен, поэтому проверка
//                   первая. Важно, что годится ЛЮБОЕ сообщение, а не только
//                   напоминание: клиент часто жмёт «Приду» сразу на подтверждении
//                   записи, за сутки до напоминания, и требование именно напоминания
//                   выбрасывало бы самых отзывчивых людей из подсчёта.
// clientConfirmed - клиент нажал в боте «Приду» (bookings.client_confirmed).
//                   Прямое действие человека внутри системы: самый честный сигнал,
//                   какой вообще возможен без опроса клиента.
// priorNoShows    - сколько раз этот клиент не являлся ДО этой брони. История неявок
//                   означает, что вероятность не прийти у него измеримо выше средней,
//                   и напоминание сработало именно на нём.
// wasOverdue      - на дату визита клиент был просрочен по своему сроку возврата,
//                   то есть уже выпал из цикла и вернулся.
export function classifyReturn({ messageSent = false, clientConfirmed = false, priorNoShows = 0, wasOverdue = false } = {}) {
  if (!messageSent) return null;
  if (clientConfirmed) return 'confirmed';
  if (Number(priorNoShows) > 0) return 'reminded_risky';
  if (wasOverdue) return 'returned_overdue';
  return null;
}

// Денежная сводка. На вход - уже размеченные визиты, на выход - общая сумма и
// разбивка по основаниям.
//
// hasMessaging - уходило ли за период хоть одно сообщение клиентам. Различие между
// null и нулём здесь такое же принципиальное, как в «Недополученной прибыли»: «бот
// ещё не заговорил» и «система работала и ничего не вернула» - разные сообщения
// владельцу, и первое нельзя показывать как второе. Ноль на неподключённом канале
// выглядел бы приговором продукту, которого тот не заслужил.
export function summarizeReturned({ visits = [], hasMessaging = true } = {}) {
  const byReason = Object.fromEntries(RETURN_REASONS.map((r) => [r, 0]));
  let total = 0;

  for (const v of visits) {
    const reason = v?.reason;
    if (!RETURN_REASONS.includes(reason)) continue;
    const amount = Number(v.amount);
    if (!Number.isFinite(amount)) continue;
    byReason[reason] += amount;
    total += amount;
  }

  return {
    total: hasMessaging ? total : null,
    byReason,
    count: visits.length,
    hasMessaging,
  };
}
