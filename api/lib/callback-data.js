// Разбор данных кнопки бота (06.09.2026).
//
// Формат один на все каналы: «<глагол>:<id>», где id - либо бронь, либо клиент.
// Вынесено из telegram.js отдельным модулем без единой зависимости, чтобы правило
// разбора можно было проверить офлайн-тестом, не поднимая базу и не трогая сеть:
// именно здесь 06.09.2026 нашёлся дефект, из-за которого не работала ни одна кнопка
// по визиту.
//
// Почему нельзя split(':'). Идентификатор брони собирается как
// `${date}-${startTime}-${masterId}-${hex}` (api/routes/bookings.js, createBookingTx),
// а startTime это «10:00» - двоеточие внутри id. Разбиение по всем двоеточиям
// возвращало обрезанный «2026-09-06-10», бронь по нему не находилась, и человек в
// ответ на каждое нажатие получал «Не нашли вашу запись».
export function parseCallbackData(data) {
  const raw = String(data ?? '');
  const sep = raw.indexOf(':');
  if (sep === -1) return { verb: raw, id: '' };
  return { verb: raw.slice(0, sep), id: raw.slice(sep + 1) };
}

// Предел Telegram на callback_data - 64 байта, и кнопка с превышением не отправляется
// вовсе: человек получает письмо без единой кнопки и молча выпадает из разговора.
// Сегодняшний максимум - «rb:» плюс id брони с id сотрудника внутри (59 байт), то
// есть запас всего 5 байт. Проверка живёт здесь, чтобы удлинение любого из
// идентификаторов упиралось в красный тест, а не в тишину у клиента.
export const CALLBACK_DATA_LIMIT = 64;

export function callbackDataFits(data) {
  return Buffer.byteLength(String(data ?? ''), 'utf8') <= CALLBACK_DATA_LIMIT;
}
