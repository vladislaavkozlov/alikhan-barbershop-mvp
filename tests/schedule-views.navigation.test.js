// Окно 25 (05.08.2026) - единое состояние даты поперёк вкладок День/Неделя/Месяц/Год.
// Юниты на чистые хелперы навигации, которые считают "какую неделю/месяц показать
// для якорной даты" и подпись-якорь под вкладками. DOM здесь не нужен: модуль
// assets/crm-schedule-shared.js (декомпозиция 07.08.2026, было в crm-schedule-views.js)
// только объявляет функции/константы (обращения к document живут в модулях видов),
// поэтому импортируется в node как обычный ES-модуль - тот же приём, что уже
// используется для api/server.mjs.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mondayOf, addMonths, viewAnchorLabel } from '../assets/crm-schedule-shared.js';

test('mondayOf: любой день недели сводится к своему понедельнику', () => {
  // 2026-08-05 - среда
  assert.equal(mondayOf('2026-08-05'), '2026-08-03');
  assert.equal(mondayOf('2026-08-03'), '2026-08-03'); // сам понедельник
  assert.equal(mondayOf('2026-08-09'), '2026-08-03'); // воскресенье принадлежит той же неделе
  // Неделя может начинаться в прошлом месяце и прошлом году
  assert.equal(mondayOf('2026-09-01'), '2026-08-31');
  assert.equal(mondayOf('2027-01-01'), '2026-12-28');
});

test('addMonths: соседний месяц берётся от первого числа, без переполнения 31-го', () => {
  assert.equal(addMonths('2026-08-05', 1), '2026-09-01');
  assert.equal(addMonths('2026-08-05', -1), '2026-07-01');
  // 31 января + 1 месяц не должен превратиться в 3 марта (классический баг setMonth)
  assert.equal(addMonths('2026-01-31', 1), '2026-02-01');
  // Переход через границу года в обе стороны
  assert.equal(addMonths('2026-12-15', 1), '2027-01-01');
  assert.equal(addMonths('2026-01-15', -1), '2025-12-01');
});

test('viewAnchorLabel/День: день недели и дата в родительном падеже', () => {
  assert.equal(viewAnchorLabel('day', '2026-08-05'), 'День · среда, 5 августа');
  assert.equal(viewAnchorLabel('day', '2026-01-01'), 'День · четверг, 1 января');
});

test('viewAnchorLabel/Неделя: диапазон понедельник-воскресенье от якорной даты', () => {
  // Якорь в середине недели - подпись всё равно про неделю целиком
  assert.equal(viewAnchorLabel('week', '2026-08-05'), 'Неделя · 3-9 августа');
  assert.equal(viewAnchorLabel('week', '2026-08-03'), 'Неделя · 3-9 августа');
});

test('viewAnchorLabel/Неделя: неделя на стыке месяцев и годов называет оба', () => {
  // 2026-07-27 (Пн) - 2026-08-02 (Вс)
  assert.equal(viewAnchorLabel('week', '2026-07-28'), 'Неделя · 27 июля - 2 августа');
  // 2026-12-28 (Пн) - 2027-01-03 (Вс): разные годы - годы обязаны быть в подписи
  assert.equal(viewAnchorLabel('week', '2026-12-31'), 'Неделя · 28 декабря 2026 - 3 января 2027');
});

test('viewAnchorLabel/Месяц: месяц и год якорной даты', () => {
  assert.equal(viewAnchorLabel('month', '2026-08-05'), 'Месяц · Август 2026');
  assert.equal(viewAnchorLabel('month', '2027-01-31'), 'Месяц · Январь 2027');
});

test('viewAnchorLabel/Год: подпись про реально нарисованный справочный календарь', () => {
  // Панель "Год" - статичный производственный календарь РФ на 2026 (crm-owner.html),
  // он не перерисовывается под якорь, поэтому подпись обязана называть именно 2026,
  // а не год якоря - иначе заголовок врал бы про содержимое панели.
  assert.equal(viewAnchorLabel('year', '2026-08-05'), 'Год · 2026 (справочный)');
  assert.equal(viewAnchorLabel('year', '2027-03-10'), 'Год · 2026 (справочный)');
});

test('viewAnchorLabel: неизвестный вид не роняет UI', () => {
  assert.equal(viewAnchorLabel('quarter', '2026-08-05'), '');
});
